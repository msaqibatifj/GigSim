"""Regenerates evals/results/RESULTS.md from the JSON result files. README and report tables are copied from that file,
so every number traces to a committed result. Missing inputs print as "n/a" (never invented).
Run: python -m evals.runners.results_table"""
import json, pathlib

RES = pathlib.Path(__file__).resolve().parents[1] / "results"


def load(name):
    p = RES / name
    return json.loads(p.read_text()) if p.exists() else None


def f(x, nd=3):
    return "n/a" if x is None else (f"{x:.{nd}f}" if isinstance(x, float) else str(x))


def table(head, rows):
    return "\n".join(["| " + " | ".join(head) + " |", "|" + "---|" * len(head)] + ["| " + " | ".join(map(str, r)) + " |" for r in rows])


def retrieval_and_pipeline():
    allp, per = load("rag_eval_all.json"), load("rag_eval_persona.json")
    out = []
    if not allp:
        return "_rag_eval_all.json missing_"
    for v, m in allp["variants"].items():
        d = load("decision_eval_open.json" if v == "v3_rerank" else f"decision_eval_open_{v}.json")
        s = d["summary"] if d else None
        p = per["variants"].get(v, {}).get("overall", {}) if per else {}
        out.append([v, f(m["overall"]["recall5"]), f(m["overall"]["ndcg10"]), f(p.get("ndcg10")),
                    f(s["proposals"]["unsupported_claims_before"]) + " -> " + f(s["proposals"]["unsupported_claims_after"]) if s else "n/a",
                    "n/a (not run)" if not s else f(s["gigsim"]["sim_reply_rate"]),
                    f(s["cost_latency"]["per_proposal"]["p95_s"], 1) if s else f(m["latency_s"]["p95"], 2) + " (retrieval only)",
                    f(s["cost_latency"]["per_proposal"]["usd_mean"], 4) if s else "n/a", f(s["bid_skip"]["accuracy"]) if s else "n/a"])
    return table(["Variant", "Recall@5 (pooled)", "nDCG@10 (pooled)", "nDCG@10 (per-persona)", "Unsupported claims / proposal (before -> after verification)",
                  "GigSim reply rate", "p95 latency s", "USD / proposal", "bid/skip accuracy"], out)


def main():
    parts = ["# RESULTS (generated by `python -m evals.runners.results_table`; do not edit)\n"]
    parts += ["## Retrieval variants (B5)\nRetrieval columns use all 30 dev jobs; pipeline columns need a full graph run, done for the shipped variant and the variants listed in the `decision_eval_open_<variant>.json` files (14 compact jobs). "
              "GigSim reply rate is the synthetic client model, not real behaviour.\n", retrieval_and_pipeline(), ""]
    ab = load("ablation.json")
    if ab:
        parts += ["## Ablation of the best pipeline (pooled setting)\n", table(["Arm", "Recall@5", "MRR", "nDCG@10", "single-evidence nDCG", "multi-evidence nDCG"],
                  [[n, f(a["overall"]["recall5"]), f(a["overall"]["mrr"]), f(a["overall"]["ndcg10"]), f(a["single_evidence"]["ndcg10"]) if a["single_evidence"] else "n/a",
                    f(a["multi_evidence"]["ndcg10"]) if a["multi_evidence"] else "n/a"] for n, a in ab["arms"].items()]),
                  f"\nnDCG@10 drop when removed: {ab['ndcg10_drop_when_removed']}\n"]
    d = load("decision_eval_open.json")
    if d:
        s = d["summary"]
        parts += [f"## Decisions, proposals, cost (profile `{d['profile']}`, {s['n_jobs']} compact dev jobs, rag `{d['rag_variant']}`)\n",
                  table(["Metric", "Value"], [["bid F1 / precision / recall", f"{s['bid_skip']['f1_bid']} / {s['bid_skip']['precision_bid']} / {s['bid_skip']['recall_bid']}"],
                         ["bid/skip accuracy", s["bid_skip"]["accuracy"]], ["scam+injection precision / recall", f"{s['scam_detection']['precision']} / {s['scam_detection']['recall']}"],
                         ["price inside fair band", s["price_in_fair_band"]], ["unsupported claims per proposal before -> after verification",
                          f"{s['proposals']['unsupported_claims_before']} -> {s['proposals']['unsupported_claims_after']}"],
                         ["critic send-backs (mean)", s["proposals"]["critic_loops_mean"]], ["GigSim sim reply / hire rate", f"{s['gigsim']['sim_reply_rate']} / {s['gigsim']['sim_hire_rate']}"],
                         ["p50 / p95 latency per job (s)", f"{s['cost_latency']['per_job']['p50_s']} / {s['cost_latency']['per_job']['p95_s']}"],
                         ["p50 / p95 latency per proposal (s)", f"{s['cost_latency']['per_proposal']['p50_s']} / {s['cost_latency']['per_proposal']['p95_s']}"],
                         ["USD per job / per proposal", f"{s['cost_latency']['per_job']['usd_mean']} / {s['cost_latency']['per_proposal']['usd_mean']}"],
                         ["tokens per job / per proposal", f"{s['cost_latency']['per_job']['tokens_mean']:.0f} / {s['cost_latency']['per_proposal']['tokens_mean']:.0f}"]]), ""]
    ac = load("agent_comparison.json")
    if ac:
        keys = [("bid_skip_accuracy", "bid/skip accuracy"), ("scam_injection_skipped", "scam/injection skipped"), ("injection_obeyed", "drafts that obeyed a planted instruction"),
                ("unsupported_per_proposal", "unsupported claims / proposal"), ("compliance_violations_in_draft", "drafts with contact/guarantee/over-length"),
                ("sim_reply_rate", "GigSim reply rate"), ("tokens_mean", "tokens / job"), ("latency_p50_s", "p50 s"), ("latency_p95_s", "p95 s"), ("errors", "errors")]
        parts += ["## Single agent vs prebuilt supervisor vs hand-built graph (Q.C)\n", table(["Metric"] + list(ac["architectures"]),
                  [[lab] + [f(a["summary"].get(k)) for a in ac["architectures"].values()] for k, lab in keys]),
                  "\n_Graph rows are post-verification/compliance drafts; baselines are raw model output, so the unsupported and compliance rows favour the graph by construction._\n"]
    tg = load("tool_granularity.json")
    if tg:
        parts += [f"## Tool granularity (Q.A; {tg['n_tasks']} tasks, model `{tg['model']}`)\n", table(["Design", "Tools", "Tool accuracy", "Argument accuracy", "Prompt tokens / task"],
                  [[k, v["n_tools"], v["tool_accuracy"], v["arg_accuracy"], v["prompt_tokens_per_task"]] for k, v in tg["designs"].items()]), ""]
    ij = load("injection_eval.json")
    if ij:
        parts += [f"## Injection defence ({ij['n']} planted posts)\n", table(["", "Attack success rate", "Flagged by Risk", "Canary reached a draft"],
                  [[arm, ij[arm]["attack_success_rate"], ij[arm]["flag_rate"], ij[arm]["canary_leak_rate"]] for arm in ("before", "after")]), ""]
    sg, xl = load("score_gap.json"), load("decision_eval_open_extra_lowfit.json")
    if sg:
        parts += ["## Does the retrieval score separate fits from non-fits? (all 42 dev jobs, best whole-post cross-encoder score)\n",
                  table(["Group", "n", "min", "median", "max"], [[k, *[sg[key][m] for m in ("n", "min", "median", "max")]] for k, key in
                        (("legit, should bid", "legit_should_bid"), ("legit, should skip", "legit_should_skip"), ("scam or injection", "scam_or_injection"))]),
                  f"\nFloor {sg['floor']}: {sg['bid_jobs_below_floor']} bid jobs below it, {sg['skip_jobs_above_floor']} of {sg['legit_should_skip']['n']} skip jobs above it; "
                  f"gap between the worst bid job and the best skip job = {sg['gap']} logits.\n"]
    if xl:
        parts += ["## Held-out low-fit jobs (not in the compact set; thresholds were tuned without them)\n",
                  table(["Job", "gold", "predicted", "fit"], [[r["id"], r["gold"], r["pred"], r["fit"]] for r in xl["rows"]]), ""]
    ex = load("ab_experiment.json")
    if ex:
        parts += [f"## X2 proposal experiment ({ex['n_jobs']} jobs)\n", f"Mean GigSim reply probability {ex['mean_p_reply']}; simulated replies {ex['sim_replies']}; "
                  f"B minus A = {ex['mean_diff_B_minus_A']}; permutation p = {ex['permutation_p_value']}. {ex['caveat']}\n"]
    jc = load("judge_calibration.json")
    parts += ["## Judge calibration\n", (f"n = {jc['n_labelled']}, quadratic-weighted kappa = {jc['weighted_kappa']}, exact agreement = {jc['exact_agreement']}, "
              f"mean human {jc['mean_human']} vs judge {jc['mean_judge']}.") if jc else "_Not run: needs the human labels (judge_labels.json)._"]
    (RES / "RESULTS.md").write_text("\n".join(parts) + "\n", encoding="utf-8")
    print("wrote", RES / "RESULTS.md")


if __name__ == "__main__":
    main()
